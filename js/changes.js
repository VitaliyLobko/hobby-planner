/** -1, 0, 1 — як у сортуванні; «0.7.10» новіше за «0.7.9». */
export function compareVersions(a, b) {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return Math.sign(d);
  }
  return 0;
}

/** Записи новіші за seen і не новіші за current. */
export const changesSince = (seen, current) =>
  CHANGES.filter((c) => compareVersions(c.v, seen) > 0 && compareVersions(c.v, current) <= 0);
